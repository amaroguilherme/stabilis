import os
import random

def generate_mock(filename, profile_type="normal"):
    """
    profile_type:
        - 'poor_metabolizer': Slow liver (defective CYP2C19). Risk of toxicity. 
        - 'warrior': Fast COMT (Low dopamine). Stress-resistant, prone to depression. 
        - 'worrier': Slow COMT (High dopamine). Anxious, does not tolerate stimulants.
    """
    
    header = """# This file was generated by Stabilis Genomics Mock Engine
                # This file contains raw genotype data.
                # rsid	chromosome	position	genotype"""

    print(f"Generating synthetic patient: {filename} ({profile_type})...")
    
    critical_snps = {}

    if profile_type == "poor_metabolizer":
        critical_snps["rs4244285"] = "AA"
    elif profile_type == "fast_metabolizer":
        critical_snps["rs4244285"] = "GG"
    else:
        critical_snps["rs4244285"] = "AG"

    if profile_type == "worrier":
        critical_snps["rs4680"] = "AA" 
    elif profile_type == "warrior":
        critical_snps["rs4680"] = "GG" 
    else:
        critical_snps["rs4680"] = "AG"

    with open(filename, "w") as f:
        f.write(header + "\n")
        
        for rsid, geno in critical_snps.items():
            f.write(f"{rsid}\t1\t000000\t{geno}\n")
            
        for i in range(50):
            rsid = f"rs{random.randint(10000, 999999)}"
            geno = random.choice(["AA", "AT", "CG", "GG", "TT"])
            f.write(f"{rsid}\t{random.randint(1,23)}\t{random.randint(1000,9999999)}\t{geno}\n")

    print(f"File '{filename}' generated.")

if __name__ == "__main__":
    if not os.path.exists("stabilis/data"):
        os.makedirs("stabilis/data", exist_ok=True)
        
    base_path = "stabilis/data"
    generate_mock(f"{base_path}/patient_toxic.txt", "poor_metabolizer")
    generate_mock(f"{base_path}/patient_anxious.txt", "worrier")
    generate_mock(f"{base_path}/patient_depressive.txt", "warrior")
    